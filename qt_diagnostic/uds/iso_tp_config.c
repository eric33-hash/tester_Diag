static int L_Data_request(can_iso_tp_link_t_p link_src, const struct CAN_msg* msg)
{
	int res = 1;
    if(tool == 0)
    {
        TPCANMsg canmsg;
        //canmsg = (TPCANMsg *)malloc(sizeof(TPCANMsg));

        canmsg.ID = msg->id.id;
        canmsg.LEN = msg->dlc;
        memcpy(canmsg.DATA,msg->data,msg->dlc);
        if(msg->id.isExt == 0)
        {
            canmsg.MSGTYPE = PCAN_MESSAGE_STANDARD;
        }
        TPCANStatus status = CAN_Write(0x51,&canmsg);

        if(status == PCAN_ERROR_OK)
        {
            res = 0;
        }
        else
        {
            print_debug_info("Requset Fail");
        }
    }
    else if(tool == 1)
    {
        VCANMsg canmsg;
        XLstatus status;
        canmsg.ID = msg->id.id;
        canmsg.LEN = msg->dlc;
        memcpy(canmsg.DATA,msg->data,dlc2len(canmsg.LEN));
        //XLstatus status = CAN_Transmit(&canmsg);
        if(link_iso.init_info.TX_DLC == 8)
            status = CAN_TransmitFD(&canmsg,1);
        else
            status = CAN_TransmitFD(&canmsg,0);
        if(status == XL_SUCCESS)
        {
            res = 0;
        }
    }
	return res;
	//todo：send frame to low layer
}
